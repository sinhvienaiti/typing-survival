/**
 * The S0 trial's golden event trace (docs/BUILD_S1.md §14 R1 step 1): 6 seeds
 * × 3 bots play the trial ("Trận thử", the S0 stage with Xung and Tia) with
 * the header their profile sets; the command logs, the event trace of the S0
 * event kinds and the final stats go to tests/golden/s0-trace.json.
 * tests/s0-trace.test.ts replays the logs and must find the same trace.
 * Regenerate only on purpose (a rule of the trial changed), and say why in
 * the changelog:
 *   node --import tsx scripts/s0-trace.ts --write
 */
import { writeFileSync } from "node:fs";
import { headerFor } from "../src/app/skill";
import { botProfile, botRows } from "./balance-lib";
import { playOut, sharedDeck, typistBot } from "../tests/survival/typist-bot";
import { encodeLog, foldEvents, newTrace } from "../tests/survival/trace";

export const TRACE_SEEDS = [1, 2, 3, 4, 5, 6];
export const TRACE_BOTS = ["novice", "standard", "fast"];
const FILE = new URL("../tests/golden/s0-trace.json", import.meta.url);

const deck = sharedDeck();
const runs = [];
for (const id of TRACE_BOTS) {
  const row = botRows().find((bot) => bot.id === id)!;
  for (const seed of TRACE_SEEDS) {
    const header = headerFor(botProfile(row, "balanced"), "balanced", true);
    const { session, bot } = typistBot({ seed, deck, ...header }, row.params, 7919 * seed + 13);
    const trace = newTrace();
    playOut(session, bot, 60 * 400, (w) => foldEvents(trace, w.events));
    const w = session.world;
    runs.push({
      bot: id, seed, header: { mode: header.mode, pace: header.pace, expected: header.expected, director: header.director },
      tick: w.tick, phase: w.phase, hp: w.hp, stats: { ...w.stats }, trace: { hash: trace.hash >>> 0, count: trace.count, kinds: trace.kinds }, log: encodeLog(session.log),
    });
  }
}
const text = JSON.stringify({ note: "S0 trial trace, generated by scripts/s0-trace.ts at 00ed734 rules", runs }, null, 1);
if (process.argv.includes("--write")) writeFileSync(FILE, text + "\n");
console.log(runs.map((run) => run.bot + " seed " + run.seed + ": " + run.phase + " hp " + run.hp + " events " + run.trace.count + " hash " + run.trace.hash.toString(16)).join("\n"));
